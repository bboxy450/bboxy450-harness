fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos")
        && std::env::var("PROFILE").as_deref() == Ok("release")
    {
        // The macOS debug map contains absolute paths to native archive members.
        // Omit it at link time, where failure cannot silently leave those paths.
        println!("cargo:rustc-link-arg-bin=bboxy450-harness=-Wl,-S");
    }
}
